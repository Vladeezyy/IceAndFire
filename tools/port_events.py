#!/usr/bin/env python3
"""NeoForge events of the game code -> the same names in dev.vladeezyy.iceandfire.bus, and the generated index of the
@SubscribeEvent methods (idempotent; run from the repository root).

    python3 -I tools/port_events.py

EventIndex lists the common listeners, ClientEventIndex the ones of classes with Dist.CLIENT. Static methods are
referenced directly; a class with instance listeners (ServerEvents) gets one instance. Events that are not in the bus
package (registration, data generation) are reported: their listeners belong in the NeoForge module.
"""
import re
from pathlib import Path

JAVA = Path("common/src/main/java")
BUS = JAVA / "dev/vladeezyy/iceandfire/bus"
PKG = "dev.vladeezyy.iceandfire.bus"
BUS_TYPES = {p.stem for p in BUS.glob("*.java")} - {"package-info", "IafBus", "EventIndex", "ClientEventIndex"}
API = {"SubscribeEvent", "EventPriority", "Event", "ICancellableEvent", "EventBusSubscriber", "Dist", "OnlyIn"}
SUB = re.compile(r"@SubscribeEvent(?:\(priority\s*=\s*EventPriority\.(\w+)\))?\s*\n(?:\s*@\w+(?:\([^)]*\))?\s*\n)*"
                 r"\s*public (static )?void (\w+)\(\s*(?:final )?([\w.]+)(?:<[^>]*>)? \w+\)")


def rewrite_imports(src):
    def repl(m):
        name = m.group(1)
        simple = name.rsplit(".", 1)[1]
        if name == "net.neoforged.fml.common.Mod":
            return ""
        if simple in BUS_TYPES or simple in API:
            return f"import {PKG}.{simple};\n"
        return m.group(0)
    return re.sub(r"import (net\.neoforged\.[\w.]+);\n", repl, src)


def main():
    common, client, skipped, instances, changed = [], [], [], {}, 0
    for path in sorted(JAVA.rglob("*.java")):
        if BUS in path.parents:
            continue
        src = path.read_text()
        new = rewrite_imports(src)
        if new != src:
            path.write_text(new)
            changed += 1
        cls = re.search(r"^public (?:final |abstract )*class (\w+)", new, re.M)
        if not cls or "@SubscribeEvent" not in new:
            continue
        pkg = re.search(r"^package ([\w.]+);", new, re.M).group(1)
        fqcn = f"{pkg}.{cls.group(1)}"
        annotation = re.search(r"@EventBusSubscriber(\([^)]*\))?\s*\n(?:@\w+[^\n]*\n)*public", new)
        is_client = bool(annotation and annotation.group(1) and "CLIENT" in annotation.group(1)) or "/client/" in path.as_posix() or cls.group(1).startswith("Client") or "Render" in cls.group(1)
        for m in SUB.finditer(new):
            prio, static, method, event = m.group(1) or "NORMAL", m.group(2), m.group(3), m.group(4)
            if event.split(".")[0] not in BUS_TYPES:
                skipped.append(f"{path.name}: {event}")
                continue
            if static:
                handler = f"{fqcn}::{method}"
            else:
                var = cls.group(1)[0].lower() + cls.group(1)[1:]
                instances[var] = fqcn
                handler = f"{var}::{method}"
            (client if is_client else common).append((event, prio, handler, None if static else var))
    for name, entries, doc in (("EventIndex", common, "The common @SubscribeEvent methods"),
                               ("ClientEventIndex", client, "The client-only @SubscribeEvent methods")):
        lines = [f"package {PKG};", "", f"/** {doc} (generated by tools/port_events.py) */", f"public final class {name} {{",
                 f"    private {name}() {{", "    }", "", "    public static void register() {"]
        for var in sorted({e[3] for e in entries if e[3]}):
            lines.append(f"        {instances[var]} {var} = new {instances[var]}();")
        for event, prio, handler, _ in sorted(entries, key=lambda e: (e[0], e[2])):
            lines.append(f"        IafBus.add({event}.class, EventPriority.{prio}, {handler});")
        lines += ["    }", "}", ""]
        (BUS / f"{name}.java").write_text("\n".join(lines))
    print(f"{changed} files rewritten; index: {len(common)} common, {len(client)} client listeners")
    for s in skipped:
        print("loader event (NeoForge module):", s)


if __name__ == "__main__":
    main()
